// FIT parser checks (run with: npx tsx src/fitparser/index.spec.ts)

let failed = 0

const assert = (cond: any, message: string) => {
    if (!cond) {
        failed++
        console.error(`FAIL: ${message}`)
    } else {
        console.log(`ok: ${message}`)
    }
}

/**
 * Minimal FIT writer, enough to encode string / enum / uint16 fields of any message.
 */
const buildFit = (messages: {mesgNum: number; fields: {num: number; type: "enum" | "uint16" | "string"; value: any}[]}[]): Buffer => {
    const CrcCalculator = require("./sdk/crc-calculator").default
    const baseTypes = {enum: 0x00, uint16: 0x84, string: 0x07}
    const data: number[] = []

    messages.forEach((mesg, localType) => {
        const values = mesg.fields.map((f) => (f.type == "string" ? Buffer.from(`${f.value}\0`, "utf8") : f.type == "uint16" ? Buffer.from([f.value & 0xff, f.value >> 8]) : Buffer.from([f.value])))
        data.push(0x40 | localType, 0, 0, mesg.mesgNum & 0xff, mesg.mesgNum >> 8, mesg.fields.length)
        mesg.fields.forEach((f, i) => data.push(f.num, values[i].length, baseTypes[f.type]))
        data.push(localType)
        values.forEach((v) => data.push(...v))
    })

    const header = Buffer.alloc(14)
    header.writeUInt8(14, 0)
    header.writeUInt8(0x20, 1)
    header.writeUInt16LE(2158, 2)
    header.writeUInt32LE(data.length, 4)
    header.write(".FIT", 8, 4, "ascii")
    header.writeUInt16LE(CrcCalculator.calculateCRC(header, 0, 12), 12)

    const combined = Buffer.concat([header, Buffer.from(data)])
    const crc = Buffer.alloc(2)
    crc.writeUInt16LE(CrcCalculator.calculateCRC(combined, 0, combined.length), 0)
    return Buffer.concat([combined, crc])
}

const main = async () => {
    const {settings} = require("setmeup")
    settings.axios = {timeout: 5000, retryInterval: 1}
    settings.fitparser = {maxFiles: 100}

    const logger = require("anyhow").default || require("anyhow")
    logger.setup("none")

    const fitparser = require("./index").default
    const database = require("../database").default
    const {encodeFitFile} = require("./builder")

    const user: any = {id: "u1", displayName: "Test User"}
    const dateStart = new Date("2026-11-10T07:00:00Z")
    const fileId = {
        mesgNum: 0,
        fields: [
            {num: 0, type: "enum" as const, value: 4},
            {num: 1, type: "uint16" as const, value: 1}
        ]
    }

    // Workout name from a FIT generated by the builder, which has no workout description.
    const built = encodeFitFile({id: 1, name: "Threshold 5x5", sportType: "Run", type: "Run", dateStart: dateStart, totalTime: 1800} as any, {time: [0, 1]} as any, {})
    let parsed = await fitparser.parse(user, {id: "built", userId: user.id, name: null}, built)
    assert(parsed.workoutName == "Threshold 5x5", `builder FIT workout name parsed (${parsed.workoutName})`)
    assert(!("workoutNotes" in parsed), "builder FIT without description does not store empty workoutNotes")

    // Workout name with notes built from the workout steps (notes, falling back to step names).
    const stepsFit = buildFit([
        fileId,
        {
            mesgNum: 26,
            fields: [
                {num: 4, type: "enum", value: 1},
                {num: 8, type: "string", value: "Final Surge Intervals"}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 0},
                {num: 0, type: "string", value: "Warmup"},
                {num: 8, type: "string", value: "Easy 10 min"}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 1},
                {num: 0, type: "string", value: "5x 1km @ threshold"},
                {num: 8, type: "string", value: ""}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 2},
                {num: 0, type: "string", value: ""},
                {num: 8, type: "string", value: " "}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 3},
                {num: 0, type: "string", value: "Cooldown"},
                {num: 8, type: "string", value: "Jog home"}
            ]
        }
    ])
    parsed = await fitparser.parse(user, {id: "steps", userId: user.id, name: null}, stepsFit)
    assert(parsed.manufacturer == "garmin", `manufacturer parsed (${parsed.manufacturer})`)
    assert(parsed.workoutName == "Final Surge Intervals", `workout name parsed (${parsed.workoutName})`)
    assert(parsed.workoutNotes == "Easy 10 min\n5x 1km @ threshold\nJog home", `workout notes built from steps (${JSON.stringify(parsed.workoutNotes)})`)

    // Workout description takes precedence over the step notes.
    const descriptionFit = buildFit([
        fileId,
        {
            mesgNum: 26,
            fields: [
                {num: 8, type: "string", value: "Long run"},
                {num: 17, type: "string", value: "Keep it easy"}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 0},
                {num: 8, type: "string", value: "Step note"}
            ]
        }
    ])
    parsed = await fitparser.parse(user, {id: "description", userId: user.id, name: null}, descriptionFit)
    assert(parsed.workoutNotes == "Keep it easy", `workout description used as notes (${parsed.workoutNotes})`)

    // Empty workout values are not stored as empty strings.
    const emptyFit = buildFit([
        fileId,
        {
            mesgNum: 26,
            fields: [
                {num: 8, type: "string", value: ""},
                {num: 17, type: "string", value: ""}
            ]
        },
        {
            mesgNum: 27,
            fields: [
                {num: 254, type: "uint16", value: 0},
                {num: 8, type: "string", value: ""}
            ]
        }
    ])
    parsed = await fitparser.parse(user, {id: "empty", userId: user.id, name: null}, emptyFit)
    assert(!("workoutName" in parsed) && !("workoutNotes" in parsed), `no empty workout name / notes stored (${JSON.stringify([parsed.workoutName, parsed.workoutNotes])})`)

    // Matching: the uploaded FIT activity wins over the API one for the same activity.
    const apiDoc = {id: "activity-123456", userId: user.id, dateStart: dateStart, totalTime: 1800, name: "API"}
    const uploadDoc = {id: `activity-upload-${user.id}-${dateStart.getTime() / 1000}`, userId: user.id, dateStart: dateStart, totalTime: 1805, name: "Upload", workoutName: "Final Surge Intervals"}
    const otherDoc = {id: "activity-999", userId: user.id, dateStart: dateStart, totalTime: 3600, name: "Other"}
    let docs: any[] = []
    database.search = async () => docs

    const stravaActivity: any = {id: 42, dateStart: dateStart, totalTime: 1800, device: "Garmin Forerunner 970"}

    docs = [apiDoc, uploadDoc, otherDoc]
    let match = await fitparser.getMatchingActivity(user, stravaActivity, "garmin")
    assert(match?.id == uploadDoc.id, `getMatchingActivity prefers the uploaded doc (${match?.id})`)

    const matches = await fitparser.getMatchingActivities(user, [stravaActivity], "garmin")
    assert(matches[42]?.id == uploadDoc.id, `getMatchingActivities prefers the uploaded doc (${matches[42]?.id})`)

    docs = [apiDoc, {...apiDoc, id: "activity-123457", workoutName: "Tempo"}]
    match = await fitparser.getMatchingActivity(user, stravaActivity, "garmin")
    assert(match?.id == "activity-123457", `getMatchingActivity prefers the doc with a workout name (${match?.id})`)

    docs = [apiDoc, otherDoc]
    match = await fitparser.getMatchingActivity(user, stravaActivity, "garmin")
    assert(match?.id == apiDoc.id, `getMatchingActivity keeps the first match otherwise (${match?.id})`)

    docs = [{...uploadDoc, totalTime: 2100}, apiDoc]
    match = await fitparser.getMatchingActivity(user, stravaActivity, "garmin")
    assert(match?.id == apiDoc.id, `getMatchingActivity keeps the stricter total time tolerance first (${match?.id})`)

    if (failed > 0) {
        console.error(`${failed} check(s) failed`)
        process.exit(1)
    }
    console.log("All checks passed")
    process.exit(0)
}

main().catch((ex) => {
    console.error(ex)
    process.exit(1)
})
